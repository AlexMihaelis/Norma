namespace Norma.Api.Data.Entities;

/// <summary>
/// Базовая единица продукта: в ней задана пищевая ценность на 100 единиц и в ней
/// ведется количество в дневнике.
/// </summary>
/// <remarks>
/// Признак нужен, чтобы не путать молоко (ккал на 100 мл) с мясом (ккал на 100 г).
/// Без плотности продукта перевести граммы в миллилитры нельзя, поэтому единица
/// записи обязана совпадать с базовой единицей продукта.
/// </remarks>
public enum FoodUnit
{
    /// <summary>Граммы: мясо, крупы, овощи, хлеб.</summary>
    Gram,

    /// <summary>Миллилитры: молоко, соки, напитки.</summary>
    Milliliter,
}
